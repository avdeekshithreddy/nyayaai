"""NyayaAI Utility functions."""
import re
from datetime import datetime


def sanitize_input(text: str) -> str:
    """Sanitize user input by stripping excess whitespace."""
    if not text:
        return ""
    return " ".join(text.split()).strip()


def truncate_text(text: str, max_length: int = 100) -> str:
    """Truncate text to a maximum length with ellipsis."""
    if not text:
        return ""
    if len(text) <= max_length:
        return text
    return text[:max_length - 3].rstrip() + "..."


def format_timestamp(timestamp_str: str) -> str:
    """Format a database timestamp to a human-readable string."""
    if not timestamp_str:
        return ""
    try:
        dt = datetime.fromisoformat(timestamp_str)
        now = datetime.now()
        diff = now - dt
        if diff.days == 0:
            if diff.seconds < 60:
                return "Just now"
            elif diff.seconds < 3600:
                mins = diff.seconds // 60
                return f"{mins}m ago"
            else:
                hours = diff.seconds // 3600
                return f"{hours}h ago"
        elif diff.days == 1:
            return "Yesterday"
        elif diff.days < 7:
            return f"{diff.days}d ago"
        else:
            return dt.strftime("%b %d, %Y")
    except (ValueError, TypeError):
        return timestamp_str


def validate_scenario(text: str) -> tuple[bool, str]:
    """Validate a legal scenario input.
    
    Returns:
        Tuple of (is_valid, error_message)
    """
    if not text or not text.strip():
        return False, "Please describe your legal scenario."
    
    cleaned = text.strip()
    if len(cleaned) < 10:
        return False, "Please provide more detail about your legal situation (at least 10 characters)."
    if len(cleaned) > 10000:
        return False, "Please keep your scenario under 10,000 characters."
    
    return True, ""


def generate_report(title: str, messages: list[dict], sources: list[dict] = None) -> str:
    """Generate a downloadable report from a conversation.
    
    Args:
        title: Conversation title.
        messages: List of message dicts with 'role' and 'content'.
        sources: Optional list of source metadata dicts.
        
    Returns:
        Formatted Markdown report string.
    """
    report_parts = [
        f"# NyayaAI Legal Analysis Report",
        f"## {title}",
        f"*Generated on: {datetime.now().strftime('%B %d, %Y at %I:%M %p')}*",
        "",
        "---",
        "",
    ]

    for msg in messages:
        if msg["role"] == "user":
            report_parts.append(f"### 📝 User Query")
            report_parts.append(msg["content"])
            report_parts.append("")
        elif msg["role"] == "assistant":
            report_parts.append(f"### ⚖️ NyayaAI Analysis")
            report_parts.append(msg["content"])
            report_parts.append("")
        report_parts.append("---")
        report_parts.append("")

    if sources:
        report_parts.append("## 📚 Referenced Legal Sources")
        report_parts.append("")
        for source in sources:
            title_str = source.get('title', 'Unknown')
            report_parts.append(f"- **{title_str}**")
            if source.get('authority'):
                report_parts.append(f"  - Authority: {source['authority']}")
            if source.get('url'):
                report_parts.append(f"  - URL: {source['url']}")
            if source.get('status') == 'replaced':
                report_parts.append(f"  - ⚠️ Replaced by: {source.get('replaced_by', 'N/A')}")
        report_parts.append("")

    report_parts.extend([
        "---",
        "",
        "## ⚠️ Disclaimer",
        "",
        "NyayaAI provides general legal information for educational purposes. "
        "It is not a substitute for advice from a qualified Indian lawyer. "
        "Laws and outcomes depend on the facts and applicable law.",
        "",
        "*This report was generated by NyayaAI — Indian Legal Scenario Analyzer*",
    ])

    return "\n".join(report_parts)


def extract_summary_from_messages(messages: list[dict]) -> str:
    """Extract a brief summary from conversation messages."""
    if not messages:
        return "No conversation started yet."
    
    # Get the first user message as scenario
    user_messages = [m for m in messages if m["role"] == "user"]
    if not user_messages:
        return "No user query found."
    
    first_query = user_messages[0]["content"]
    return truncate_text(first_query, 200)


def count_sources_in_response(response: str) -> int:
    """Count approximate number of legal references in a response."""
    patterns = [
        r'\bAct[,\s]',
        r'\bSection\s+\d+',
        r'\bArticle\s+\d+',
        r'\bSanhita\b',
        r'\bCode\b',
    ]
    count = 0
    for pattern in patterns:
        count += len(re.findall(pattern, response, re.IGNORECASE))
    return min(count, 20)  # Cap at reasonable number
